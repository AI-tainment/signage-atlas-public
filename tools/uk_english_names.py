    root = Path(__file__).resolve().parents[1]
    uk = root / "countries" / "uk"
    ov = json.loads((uk / "overlay.json").read_text())
    signs = ov.setdefault("signs", {})
    live = json.loads((uk / "signs.json").read_text())
    missing = []
    for s in live:
        code = s["id"]
        name = caption(code, s.get("name"))
        if _is_generic(name, code) or code not in NAMES:
            missing.append(code)
        rec = signs.get(code) or {}
        rec["name"] = name
        rec["what"] = blurb(code, name)
        if s.get("glyph"):
            rec["glyph"] = True
            rec["renderer"] = code
        signs[code] = rec
    (uk / "overlay.json").write_text(json.dumps(ov, indent=2) + "\n")
    print(f"overlay signs {len(signs)}")
    print("missing from NAMES or still generic:", missing)
