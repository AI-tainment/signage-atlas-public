def caption(code: str, fallback: str | None = None) -> str:
    if code in NAMES:
        return NAMES[code]
    if fallback and not _is_generic(fallback, code):
        return fallback
    return fallback or "Traffic sign"


def blurb(code: str, name: str | None = None) -> str:
    if code in WHAT:
        return WHAT[code]
    return name or NAMES.get(code) or "Traffic sign"


def _is_generic(name: str, code: str) -> bool:
    n = name or ""
    if n.startswith("TSRGD "):
        return True
    if code and re.search(rf"[\s(]{re.escape(code)}[)\s]|$", n):
        # "Warning sign (504.2)" or trailing diagram number — not "stack type"
        if f"({code})" in n or n.strip().endswith(code):
            return True
    prefixes = (
        "Warning sign", "Prohibitory roundel", "Motorway direction",
        "Non-primary direction", "Information plate", "Tourist destination",
        "Traffic signal head", "Primary-route direction", "Mandatory roundel",
        "Pedestrian signal / crossing furniture", "Road works",
    )
    return n in prefixes


